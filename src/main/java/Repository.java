import java.util.List;
import java.util.Optional;

/**
 * Обобщённый интерфейс репозитория для управления сущностями.
 *
 * @param <T> тип сущности
 */
interface Repository<T> {
    /**
     * Добавляет сущность в репозиторий.
     *
     * @param item сущность для добавления
     */
    void add(T item);

    /**
     * Удаляет сущность из репозитория.
     *
     * @param item сущность для удаления
     * @return true, если сущность была удалена, false иначе
     */
    boolean remove(T item);

    /**
     * Находит сущность по идентификатору.
     *
     * @param id идентификатор сущности
     * @return Optional, содержащий сущность, если найдена
     */
    Optional<T> findById(String id);

    /**
     * Возвращает все сущности из репозитория.
     *
     * @return список всех сущностей
     */
    List<T> findAll();

    /**
     * Возвращает количество сущностей в репозитории.
     *
     * @return количество сущностей
     */
    int count();

    /**
     * Очищает репозиторий, удаляя все сущности.
     */
    void clear();
}
